export const MOTIVATION_KEYS = Array.from({ length: 10 }, (_, i) => `m${i + 1}`);

export function lineFor(key, coach) {
  const v = VOICE_LINES[key];
  if (v == null) return null;
  return typeof v === 'string' ? v : v[coach];
}
